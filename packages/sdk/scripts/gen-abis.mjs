// Generates typed `as const` ABI modules from Foundry build output (contracts/out).
// Run after `forge build --root contracts`.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, '..', '..', 'contracts', 'out');
const target = join(root, 'src', 'abis');

// Contract name -> export name. "File:Contract" reads an artifact declared in another source file.
const CONTRACTS = {
  VaultManager: 'vaultManagerAbi',
  PToken: 'pTokenAbi',
  OracleRouter: 'oracleRouterAbi',
  WormholeAdapter: 'wormholeAdapterAbi',
  SpokeGateway: 'spokeGatewayAbi',
  LeverageManager: 'leverageManagerAbi',
  KeeperGateway: 'keeperGatewayAbi',
  IWormhole: 'wormholeAbi',
  InterestRateModel: 'interestRateModelAbi',
  MockPyth: 'mockPythAbi',
  'SupraSource:ISupraOraclePull': 'supraPullAbi',
  IPriceSource: 'priceSourceAbi',
};

mkdirSync(target, { recursive: true });
const exports = [];
for (const [entry, exportName] of Object.entries(CONTRACTS)) {
  const [file, name] = entry.includes(':') ? entry.split(':') : [entry, entry];
  const artifact = JSON.parse(readFileSync(join(out, `${file}.sol`, `${name}.json`), 'utf8'));
  const from = file === name ? `contracts/out/${file}.sol` : `contracts/out/${file}.sol (${name})`;
  writeFileSync(
    join(target, `${exportName}.ts`),
    `// Generated by scripts/gen-abis.mjs from ${from} — do not edit.\nexport const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
  );
  exports.push(`export { ${exportName} } from './${exportName}';`);
}
writeFileSync(join(target, 'index.ts'), `${exports.join('\n')}\n`);
console.log(`wrote ${exports.length} ABIs to ${target}`);
